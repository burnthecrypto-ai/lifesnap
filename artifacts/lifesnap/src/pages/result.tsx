import { useEffect, useRef } from "react";
import { useLocation } from "wouter";
import { motion } from "framer-motion";
import {
  Copy, Printer, BookmarkPlus,
  FileText, ListChecks, Clock, Users, FileQuestion,
  AlertCircle, Play, Tag, Share2, ArrowLeft,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { useApp } from "@/lib/context";
import { useCreateSnapshot, getListSnapshotsQueryKey } from "@workspace/api-client-react";
import { useQueryClient } from "@tanstack/react-query";
import { useToast } from "@/hooks/use-toast";

const PINK   = "hsl(330 100% 62%)";
const CYAN   = "hsl(188 100% 54%)";
const PURPLE = "hsl(272 95% 68%)";
const ORANGE = "hsl(28 100% 58%)";
const AMBER  = "hsl(45 100% 60%)";

function SectionLabel({ icon, label, color }: { icon: React.ReactNode; label: string; color: string }) {
  return (
    <div className="flex items-center gap-2 mb-3">
      <span style={{ color, filter: `drop-shadow(0 0 6px ${color})` }}>{icon}</span>
      <span className="text-[10px] font-black uppercase tracking-widest font-mono" style={{ color, textShadow: `0 0 8px ${color}80` }}>
        {label}
      </span>
    </div>
  );
}

export default function ResultPage() {
  const [, setLocation] = useLocation();
  const { currentResult } = useApp();
  const { toast } = useToast();
  const queryClient = useQueryClient();
  const createSnapshot = useCreateSnapshot();
  const contentRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!currentResult) setLocation("/");
  }, [currentResult, setLocation]);

  if (!currentResult) return null;

  const { diaryEntry, snapshot, mode } = currentResult;

  const handleCopy = () => {
    const t = `LIFESNAP CASE REPORT
====================
SITUATION SUMMARY:
${snapshot.situationSummary}

KEY FACTS:
${snapshot.keyFacts.map(f => `• ${f}`).join("\n")}

TIMELINE:
${snapshot.timeline.map(i => `${i.date} — ${i.event}`).join("\n")}

PEOPLE INVOLVED:
${snapshot.peopleInvolved.join(", ")}

NEXT 3 ACTIONS:
${snapshot.nextThreeActions.map((a, i) => `${i + 1}. ${a}`).join("\n")}

RISKS & DEADLINES:
${snapshot.risksAndDeadlines.map(r => `• ${r}`).join("\n")}

MISSING INFORMATION:
${snapshot.missingInformation.map(m => `• ${m}`).join("\n")}

TAGS: ${snapshot.tags.map(t => `#${t}`).join(" ")}

SHAREABLE SUMMARY:
${snapshot.shareableSummary}

---
Generated by LifeSnap DAAI007. Not medical/legal/financial advice.`;
    navigator.clipboard.writeText(t);
    toast({ title: "Copied", description: "Plain-text report copied to clipboard." });
  };

  const handleSave = () => {
    createSnapshot.mutate({
      data: {
        originalText: "Input text hidden for privacy",
        mode, diaryEntry, snapshot,
        title: snapshot.situationSummary.substring(0, 50) + "...",
      },
    }, {
      onSuccess: () => {
        toast({ title: "Saved", description: "Your LifeSnap has been saved." });
        queryClient.invalidateQueries({ queryKey: getListSnapshotsQueryKey() });
        setLocation("/snapshots");
      },
      onError: () => toast({ title: "Error", description: "Failed to save snapshot.", variant: "destructive" }),
    });
  };

  return (
    <div className="flex-1 flex flex-col relative h-full bg-background print:bg-white print:text-black">

      {/* ── Sticky sub-header ── */}
      <div className="p-4 flex items-center gap-3 sticky top-0 z-10 print:hidden"
        style={{
          background: "hsl(240 18% 2% / .97)",
          backdropFilter: "blur(20px)",
          borderBottom: `2px solid ${PINK}40`,
          boxShadow: `0 2px 20px ${PINK}18`,
        }}>
        <button
          onClick={() => setLocation("/")}
          className="p-2 rounded-lg text-muted-foreground hover:text-white transition-colors"
          style={{ border: "1px solid hsl(240 10% 18%)" }}
        >
          <ArrowLeft className="w-4 h-4" />
        </button>
        <span className="w-2.5 h-2.5 rounded-full animate-pulse"
          style={{ background: PINK, boxShadow: `0 0 8px ${PINK}, 0 0 20px ${PINK}60` }} />
        <h2 className="font-black uppercase tracking-widest text-sm"
          style={{ color: PINK, textShadow: `0 0 10px ${PINK}` }}>
          Case Report Generated
        </h2>
      </div>

      {/* ── Content ── */}
      <div className="flex-1 overflow-y-auto p-4 space-y-6 pb-28" ref={contentRef}>

        {/* Diary entry */}
        <motion.div initial={{ opacity: 0, y: 12 }} animate={{ opacity: 1, y: 0 }}>
          <div className="card-purple rounded-xl overflow-hidden">
            <div className="px-4 py-3 border-b-2 flex items-center gap-2"
              style={{ borderColor: `${PURPLE}40`, background: `hsl(272 30% 8% / .8)` }}>
              <FileText className="w-3.5 h-3.5" style={{ color: PURPLE, filter: `drop-shadow(0 0 5px ${PURPLE})` }} />
              <span className="text-[10px] font-black uppercase tracking-widest font-mono"
                style={{ color: PURPLE, textShadow: `0 0 8px ${PURPLE}` }}>Raw Input Record</span>
            </div>
            <div className="px-4 py-4">
              <p className="text-white/85 leading-relaxed font-serif text-base italic">"{diaryEntry.content}"</p>
              <p className="text-[10px] text-muted-foreground mt-4 text-right font-mono uppercase tracking-widest border-t border-border/30 pt-2">
                {new Date(diaryEntry.createdAt).toLocaleString(undefined, { dateStyle: "medium", timeStyle: "short" })}
              </p>
            </div>
          </div>
        </motion.div>

        {/* Section header */}
        <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} transition={{ delay: 0.08 }}>
          <div className="flex items-center gap-3 mb-6 pb-3"
            style={{ borderBottom: `1px solid hsl(240 10% 18%)` }}>
            <span className="w-1.5 h-7 rounded-sm"
              style={{ background: `linear-gradient(180deg, ${CYAN}, ${PURPLE})`, boxShadow: `0 0 10px ${CYAN}80` }} />
            <h3 className="text-xl font-black uppercase tracking-widest text-white"
              style={{ textShadow: "0 0 18px hsl(0 0% 100% / .4), 0 0 40px hsl(188 100% 54% / .25)" }}>
              Structured Intelligence
            </h3>
          </div>
        </motion.div>

        {/* Situation summary */}
        <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.1 }}>
          <SectionLabel icon={<ListChecks className="w-4 h-4" />} label="Situation Summary" color={CYAN} />
          <div className="p-4 rounded-xl text-sm text-white/90 leading-relaxed"
            style={{ background: `hsl(188 30% 7% / .9)`, border: `2px solid ${CYAN}50`, boxShadow: `0 0 16px ${CYAN}15, inset 0 1px 0 ${CYAN}10` }}>
            {snapshot.situationSummary}
          </div>
        </motion.div>

        {/* Next actions */}
        <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.15 }}>
          <SectionLabel icon={<Play className="w-4 h-4" />} label="Required Actions" color={PINK} />
          <ul className="space-y-3">
            {snapshot.nextThreeActions.map((action, i) => (
              <li key={i} className="flex gap-4 p-4 rounded-xl items-start"
                style={{ background: `hsl(330 30% 7% / .9)`, border: `2px solid ${PINK}45`, boxShadow: `0 0 14px ${PINK}12, inset 0 1px 0 ${PINK}10` }}>
                <span className="font-mono font-black text-xl leading-none mt-0.5 shrink-0"
                  style={{ color: PINK, textShadow: `0 0 10px ${PINK}`, minWidth: 20 }}>{i + 1}</span>
                <span className="text-sm text-white/90 leading-relaxed">{action}</span>
              </li>
            ))}
          </ul>
        </motion.div>

        {/* Key facts */}
        <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.2 }}>
          <SectionLabel icon={<FileText className="w-4 h-4" />} label="Key Facts" color={PURPLE} />
          <ul className="space-y-2">
            {snapshot.keyFacts.map((fact, i) => (
              <li key={i} className="flex gap-3 items-start text-sm text-white/85 pb-2 border-b border-border/25 last:border-0">
                <span className="w-1.5 h-1.5 rounded-full mt-2 shrink-0"
                  style={{ background: PURPLE, boxShadow: `0 0 6px ${PURPLE}` }} />
                {fact}
              </li>
            ))}
          </ul>
        </motion.div>

        {/* Timeline */}
        {snapshot.timeline.length > 0 && (
          <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.25 }}>
            <SectionLabel icon={<Clock className="w-4 h-4" />} label="Chronology" color={CYAN} />
            <div className="space-y-4 relative">
              <div className="absolute left-[11px] top-0 bottom-0 w-px"
                style={{ background: `linear-gradient(180deg, ${CYAN}60, ${PURPLE}40)` }} />
              {snapshot.timeline.map((item, i) => (
                <div key={i} className="flex gap-5 relative">
                  <div className="w-6 h-6 rounded-full shrink-0 flex items-center justify-center z-10"
                    style={{ background: "hsl(240 18% 3%)", border: `2px solid ${CYAN}`, boxShadow: `0 0 10px ${CYAN}60` }} />
                  <div className="pb-3 flex-1">
                    <p className="text-[10px] font-black uppercase tracking-widest font-mono mb-1"
                      style={{ color: CYAN, textShadow: `0 0 6px ${CYAN}` }}>{item.date}</p>
                    <p className="text-sm text-white/85">{item.event}</p>
                  </div>
                </div>
              ))}
            </div>
          </motion.div>
        )}

        {/* Risks */}
        {snapshot.risksAndDeadlines.length > 0 && (
          <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.3 }}>
            <div className="p-4 rounded-xl"
              style={{ background: `hsl(28 30% 6% / .9)`, border: `2px solid ${ORANGE}60`, boxShadow: `0 0 18px ${ORANGE}20, inset 0 1px 0 ${ORANGE}12` }}>
              <SectionLabel icon={<AlertCircle className="w-4 h-4" />} label="Risks & Deadlines" color={ORANGE} />
              <ul className="space-y-2 text-sm text-white/90">
                {snapshot.risksAndDeadlines.map((r, i) => (
                  <li key={i} className="flex gap-2 items-start">
                    <span className="font-black shrink-0" style={{ color: ORANGE }}>!</span>
                    {r}
                  </li>
                ))}
              </ul>
            </div>
          </motion.div>
        )}

        {/* People & missing */}
        <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.35 }} className="grid gap-4">
          {snapshot.peopleInvolved.length > 0 && (
            <div className="glass-panel p-4 rounded-xl">
              <SectionLabel icon={<Users className="w-3.5 h-3.5" />} label="Entity Index" color={CYAN} />
              <div className="flex flex-wrap gap-2">
                {snapshot.peopleInvolved.map((p, i) => (
                  <span key={i} className="px-3 py-1 text-[10px] font-mono uppercase tracking-wider rounded-full text-white/80"
                    style={{ border: `1px solid ${CYAN}50`, background: `${CYAN}10` }}>{p}</span>
                ))}
              </div>
            </div>
          )}
          {snapshot.missingInformation.length > 0 && (
            <div className="card-purple rounded-xl p-4">
              <SectionLabel icon={<FileQuestion className="w-3.5 h-3.5" />} label="Intel Gaps" color={PURPLE} />
              <ul className="space-y-1.5 text-xs font-mono text-white/80">
                {snapshot.missingInformation.map((m, i) => (
                  <li key={i} className="flex gap-2"><span style={{ color: PURPLE }}>?</span>{m}</li>
                ))}
              </ul>
            </div>
          )}
        </motion.div>

        {/* Tags */}
        <motion.div initial={{ opacity: 0 }} animate={{ opacity: 1 }} transition={{ delay: 0.4 }}
          className="flex flex-wrap gap-2 pt-4 border-t border-border/25">
          <Tag className="w-4 h-4 text-muted-foreground/40 mr-1" />
          {snapshot.tags.map((tag, i) => (
            <span key={i} className="px-2.5 py-1 text-[9px] font-mono uppercase tracking-widest rounded-sm text-muted-foreground"
              style={{ border: "1px solid hsl(240 10% 18%)", background: "hsl(240 14% 8%)" }}>
              #{tag}
            </span>
          ))}
        </motion.div>

        {/* Shareable summary */}
        <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} transition={{ delay: 0.45 }}>
          <div className="card-pink rounded-xl p-5 relative overflow-hidden">
            <div className="absolute inset-0 scan-line opacity-30" />
            <div className="relative z-10">
              <SectionLabel icon={<Share2 className="w-4 h-4" />} label="Export Payload" color={PINK} />
              <p className="text-xs font-mono text-white/75 leading-relaxed p-3 rounded-lg"
                style={{ background: "hsl(0 0% 0% / .5)", border: `1px solid ${PINK}25` }}>
                {snapshot.shareableSummary}
              </p>
            </div>
          </div>
        </motion.div>

      </div>

      {/* ── Fixed action bar ── */}
      <div className="fixed bottom-0 left-0 right-0 max-w-[430px] mx-auto p-4 print:hidden z-20"
        style={{
          background: "hsl(240 18% 2% / .97)",
          backdropFilter: "blur(24px)",
          borderTop: `2px solid hsl(240 10% 16%)`,
          boxShadow: `0 -4px 30px hsl(0 0% 0% / .5)`,
        }}>
        <div className="flex gap-2.5">
          <button
            onClick={handleCopy}
            className="flex-1 h-12 flex items-center justify-center gap-2 font-black text-[10px] uppercase tracking-widest font-mono rounded-lg transition-all hover:scale-[1.02]"
            style={{
              border: `2px solid ${CYAN}70`,
              background: `hsl(188 40% 8%)`,
              color: CYAN,
              boxShadow: `0 0 12px ${CYAN}30`,
              textShadow: `0 0 6px ${CYAN}`,
            }}
            data-testid="button-copy"
          >
            <Copy className="w-4 h-4" /> Copy
          </button>
          <button
            onClick={() => window.print()}
            className="flex-1 h-12 flex items-center justify-center gap-2 font-black text-[10px] uppercase tracking-widest font-mono rounded-lg text-muted-foreground hover:text-white transition-all"
            style={{ border: "1px solid hsl(240 10% 18%)", background: "hsl(240 14% 8%)" }}
            data-testid="button-print"
          >
            <Printer className="w-4 h-4" /> Print
          </button>
          <button
            onClick={handleSave}
            disabled={createSnapshot.isPending}
            className="flex-[2] h-12 flex items-center justify-center gap-2 font-black text-xs uppercase tracking-widest rounded-lg btn-dayglo-pink disabled:opacity-40 disabled:cursor-not-allowed disabled:transform-none"
            data-testid="button-save"
          >
            <BookmarkPlus className="w-4 h-4" />
            {createSnapshot.isPending ? "Saving..." : "Save Log"}
          </button>
        </div>
      </div>
    </div>
  );
}
